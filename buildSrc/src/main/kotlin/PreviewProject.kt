import org.gradle.api.DefaultTask
import org.gradle.api.Project
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction

/**
 * The checked preview properties of this build.
 *
 * @throws PreviewConfigException naming the first invalid property.
 */
fun Project.previewProperties(): PreviewProperties =
    PreviewProperties.parse(
        read = { name -> providers.gradleProperty(name).orNull },
        fileExists = { path -> rootProject.file(path).isFile },
    )

/**
 * The Gradle property [name], which every build of this repository defines in `gradle.properties`.
 */
fun Project.requiredProperty(name: String): String =
    providers.gradleProperty(name).orNull
        ?: throw PreviewConfigException("Gradle property '$name' is not set.")

/**
 * Writes the xcconfig the iOS project includes: the associated domain, the Team ID and the bundle
 * identifier, all from the preview properties. The file is generated and gitignored.
 */
abstract class GenerateIosConfig : DefaultTask() {
    @get:Input abstract val previewHost: Property<String>

    @get:Input abstract val teamId: Property<String>

    @get:Input abstract val bundleId: Property<String>

    @get:OutputFile abstract val outputFile: RegularFileProperty

    @TaskAction
    fun generate() {
        outputFile
            .get()
            .asFile
            .writeText(
                "// Generated by :app:generateIosConfig from the preview Gradle properties. Do not edit.\n" +
                    "PREVIEW_HOST=${previewHost.get()}\n" +
                    "TEAM_ID=${teamId.get()}\n" +
                    "PRODUCT_BUNDLE_IDENTIFIER=${bundleId.get()}\n"
            )
    }
}
