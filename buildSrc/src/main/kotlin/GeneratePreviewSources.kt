/**
 * Kotlin source text for a string literal holding [text]; every non-ASCII or special character is
 * escaped.
 */
fun kotlinStringLiteral(text: String): String = buildString {
    append('"')
    for (c in text) {
        when {
            c == '\\' -> append("\\\\")
            c == '"' -> append("\\\"")
            c == '$' -> append("\\$")
            c == '\n' -> append("\\n")
            c == '\r' -> append("\\r")
            c == '\t' -> append("\\t")
            c.code < 0x20 || c.code > 0x7E ->
                append("\\u").append(c.code.toString(16).padStart(4, '0'))
            else -> append(c)
        }
    }
    append('"')
}

/**
 * Kotlin source for an expression that evaluates to [text]: a `chunks(...)` call over pieces of at
 * most [chunkChars] characters, because a class-file constant cannot exceed 65535 bytes.
 */
fun kotlinChunkedExpression(text: String, chunkChars: Int = 12_000): String =
    text.chunked(chunkChars).joinToString(prefix = "chunks(", postfix = ")") {
        kotlinStringLiteral(it)
    }

/**
 * Writes the sources that carry the Gradle properties into the app: `PreviewConfig.kt` (origin,
 * caps, company renderers as plain object references) and `PreviewCatalogJson.kt` (the catalogs'
 * JSON as string expressions). Nothing is read at run time (C5).
 */
abstract class GeneratePreviewSources : DefaultTask() {
    @get:Input abstract val serverOrigin: Property<String>

    @get:Input @get:Optional abstract val maxComponents: Property<Int>

    @get:Input @get:Optional abstract val maxPayloadBytes: Property<Int>

    @get:Input @get:Optional abstract val maxFrameBytes: Property<Long>

    @get:Input abstract val companyRenderers: ListProperty<String>

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val builtInCatalogs: ConfigurableFileCollection

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val companyCatalogs: ConfigurableFileCollection

    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val dir = outputDir.get().asFile.resolve("dev/fediim/anysdui/preview")
        dir.deleteRecursively()
        dir.mkdirs()
        val renderers = companyRenderers.get().joinToString("") { "        $it,\n" }
        dir.resolve("PreviewConfig.kt")
            .writeText(
                """
                // Generated by generatePreviewSources from the Gradle properties. Do not edit.
                package dev.fediim.anysdui.preview

                import dev.fediim.anysdui.runtime.CatalogRenderer

                internal object PreviewConfig {
                    const val SERVER_ORIGIN: String = ${kotlinStringLiteral(serverOrigin.get())}
                    val MAX_COMPONENTS: Int? = ${maxComponents.orNull}
                    val MAX_PAYLOAD_BYTES: Int? = ${maxPayloadBytes.orNull}
                    val MAX_FRAME_BYTES: Long? = ${maxFrameBytes.orNull?.let { "${it}L" }}
                    val companyRenderers: List<CatalogRenderer> = listOf(
                $renderers    )
                }
                """
                    .trimIndent() + "\n"
            )
        fun jsonList(files: ConfigurableFileCollection) =
            files.files.joinToString("") { "        ${kotlinChunkedExpression(it.readText())},\n" }
        dir.resolve("PreviewCatalogJson.kt")
            .writeText(
                """
                // Generated by generatePreviewSources from the catalog JSON files. Do not edit.
                package dev.fediim.anysdui.preview

                private fun chunks(vararg parts: String): String = parts.joinToString("")

                internal object PreviewCatalogJson {
                    val builtIn: List<String> = listOf(
                ${jsonList(builtInCatalogs)}    )
                    val company: List<String> = listOf(
                ${jsonList(companyCatalogs)}    )
                }
                """
                    .trimIndent() + "\n"
            )
    }
}
